/// Spacing scale. [page] is the side margin of every screen's content; [section] separates sections; [base]/[md] are
/// the gaps inside cards and between rows.
class AppSpacing {
  const AppSpacing._();

  static const double xxs = 2.0;
  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 12.0;
  static const double base = 16.0;
  static const double lg = 20.0;
  static const double xl = 24.0;
  static const double xxl = 32.0;
  static const double xxxl = 40.0;
  static const double huge = 48.0;
  static const double section = 28.0;

  /// Side margin of page content.
  static const double page = 20.0;

  /// Inner padding of a standard card.
  static const double card = 16.0;
}
